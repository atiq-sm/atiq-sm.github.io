// Builds the GitHub profile README (github.com/atiq-sm): README.md and the art
// it shows, into one folder, ready to be the contents of the atiq-sm/atiq-sm
// repository. The words come from src/data/site.js and the illustrations from
// src/viz/, so the profile says and shows what the site does.
//
//   npm run generate:readme              # into profile/
//   npm run generate:readme -- ../atiq-sm   # straight into a checkout of the profile repo

import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { site } from '../../src/data/site.js';
import { W, band, button, chart, head, hero, stack } from './art.mjs';
import { fetchCard } from './fetch.mjs';
import { SITE, TILES, TILE_W, renderRow } from './tiles.mjs';

const out = resolve(process.argv[2] ?? 'profile');
const assets = join(out, 'assets');
mkdirSync(assets, { recursive: true });

const written = [];
const save = (name, data) => {
  writeFileSync(join(assets, name), data);
  written.push([name, data.length]);
  return `assets/${name}`;
};
const attr = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const md = (s) => s.replace(/</g, '&lt;');
const img = (src, alt, width) => `<img src="${src}" width="${width}" alt="${attr(alt)}">`;
const link = (href, inner) => `<a href="${href}">${inner}</a>`;

const { links } = site;
const pocus = site.projects.find((p) => p.slug === 'mr-pocus');
const cardalive = site.projects.find((p) => p.slug === 'cardalive');

// ---------------------------------------------------------------- the art

const top = hero();
const heroSrc = save('hero.svg', top.svg);

const BUTTONS = [
  ['Portfolio', SITE, true],
  ['cardalive.xyz', cardalive.liveHref],
  ['LinkedIn', links.linkedin],
  ['Email', `mailto:${links.email}`],
];
const buttons = BUTTONS.map(([label, href, primary]) => {
  const b = button(label, { primary });
  const src = save(`button-${label.toLowerCase().replace(/[^a-z]+/g, '-')}.svg`, b.svg);
  return link(href, `<img src="${src}" height="${b.height}" alt="${attr(label)}">`);
});

const fetch = fetchCard();
const fetchSrc = save('neofetch.gif', fetch.gif);

const WORK_LEAD = 'Two mixed-reality products, an agent pipeline, and the systems work underneath: a kernel and a physics engine from scratch.'; // as in src/pages/Home.jsx
const workHead = save('head-work.svg', head('Selected work.', WORK_LEAD).svg);

const tiles = [];
for (let i = 0; i < TILES.length; i += 2) {
  for (const t of renderRow(TILES.slice(i, i + 2))) tiles.push({ ...t, src: save(t.file, t.gif) });
}
// two to a row; a little under half each, so the space between them never wraps
const tileImg = (t) => link(t.href, img(t.src, t.alt, '49.3%'));

const study = pocus.story.results;
const chartSrc = save('chart-mr-pocus.svg', chart(study.chart).svg);
const tools = save('tools.svg', stack().svg);
const close = band();
const bandSrc = save('band.svg', close.svg);

// ------------------------------------------------------------ the README

const steps = cardalive.story.sections.find((s) => s.steps)?.steps ?? [];
const work = site.experience.filter((e) => e.kind === 'work');
const school = site.experience.filter((e) => e.kind === 'education');

const readme = `<!-- Generated by scripts/readme/build.mjs in atiq-sm/atiq-sm.github.io, from the site's own content and illustrations. Edit there and regenerate. -->

${link(SITE, img(heroSrc, `${site.name}: XR engineer. Mixed reality that works in real rooms. ${site.intro.lede}`, '100%'))}

<p>
${buttons.join('\n')}
</p>

${link(`${SITE}/about/`, img(fetchSrc, fetch.alt, '100%'))}

${link(`${SITE}/work/`, img(workHead, `Selected work. ${WORK_LEAD}`, '100%'))}

<p align="center">
${tiles.slice(0, 2).map(tileImg).join('\n')}
</p>

<details>
<summary><b>The MR POCUS study:</b> all 16 mixed-reality learners told the pathologies apart, against 5 of 16 on standardized patients</summary>
<br>

${img(chartSrc, study.chart.caption, '100%')}

${md(study.lede)}

${study.items.map(([value, what]) => `- **${value}** · ${md(what)}`).join('\n')}

${link(`${SITE}/work/mr-pocus/`, 'Read the case study, with footage from the headset →')}

</details>

<details>
<summary><b>How CardAlive works:</b> from a printed card to a monster standing on your real table, in five steps</summary>
<br>

${steps.map(([name, what], i) => `${i + 1}. **${name}.** ${md(what)}`).join('\n')}

${link(`${SITE}/work/cardalive/`, 'Watch it play, recorded through a Quest 3 →')}

</details>

<p align="center">
${tiles.slice(2, 4).map(tileImg).join('\n')}
</p>
<p align="center">
${tiles.slice(4, 6).map(tileImg).join('\n')}
</p>

<details>
<summary><b>Experience:</b> ${work[0].role} at ${work[0].company}; before that, ${work.slice(1).map((e) => e.company.replace(/Northeastern University \((.*)\) & /, '$1 × ').replace(/ LLC$/, '')).join(', ').replace(/, ([^,]*)$/, ' and $1')}</summary>
<br>

${[...work, ...school]
  .map((e) => `**${md(e.role)}** · ${md(e.company)}  \n<sub>${md(e.period)}${e.location ? ` · ${md(e.location)}` : ''}</sub>\n\n${e.bullets.slice(0, 2).map((b) => `- ${md(b)}`).join('\n')}`)
  .join('\n\n')}

${link(`${SITE}/about/#experience`, 'The full history →')}

</details>

${link(`${SITE}/work/`, img(tools, 'Tools: Unity 6, C#, Meta Quest 3, OpenXR, MRUK, Blender, OpenCV; Python, LangGraph, MCP, Ollama, FastAPI, pgvector, Whisper; TypeScript, React, Next.js, Phaser 3, Socket.IO, Web Audio; C, AArch64, Raspberry Pi, Postgres, Docker, GitHub Actions.', '100%'))}

${link(`mailto:${links.email}`, img(bandSrc, `${site.cta.title} ${site.cta.lede} ${links.email}`, '100%'))}

<sub>Drawn with the same scene kit and dither as ${link(SITE, 'atiq-sm.github.io')}, and rendered to GIF by ${link(`${links.source}/tree/main/scripts/readme`, 'scripts/readme')}.</sub>
`;

writeFileSync(join(out, 'README.md'), readme);

const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
for (const [name, size] of written) console.log(`  assets/${name.padEnd(26)} ${kb(size).padStart(7)}`);
console.log(`  README.md, ${written.length} assets, ${kb(written.reduce((a, [, s]) => a + s, 0))} in all, in ${out}`);
console.log(`  (tiles are ${TILE_W}px wide, the rest ${W}px)`);
